#!/usr/bin/env python3
"""Rasterize DejaVu Sans Mono (Bitstream Vera license) into a 1-bit 6x11 font
header for the 3DS bottom-screen UI. Covers ASCII 32-126 plus Latin-1 0xA0-0xFF
so Spanish text (á é í ó ú ñ ¿ ¡) renders. Run:
    python3 make_font.py DejaVuSansMono.ttf ../source/font_6x11.hpp
"""
import sys
from PIL import Image, ImageDraw, ImageFont

W, H, SIZE = 6, 11, 10
font = ImageFont.truetype(sys.argv[1], SIZE)
codes = list(range(32, 127)) + list(range(0xA0, 0x100))
ascent = font.getmetrics()[0]

rows = []
for code in codes:
    img = Image.new("L", (W, H), 0)
    ImageDraw.Draw(img).text((0, H - 2 - ascent), chr(code), font=font, fill=255)
    glyph = []
    for y in range(H):
        bits = 0
        for x in range(W):
            if img.getpixel((x, y)) >= 110:
                bits |= 1 << (W - 1 - x)
        glyph.append(bits)
    rows.append((code, glyph))

with open(sys.argv[2], "w", encoding="utf-8") as out:
    out.write("// Generated by tools/make_font.py from DejaVu Sans Mono.\n")
    out.write("// DejaVu fonts: Bitstream Vera license (permissive). Do not edit.\n")
    out.write("#pragma once\n#include <cstdint>\n\nnamespace pd3ds::font {\n")
    out.write(f"inline constexpr int width = {W};\ninline constexpr int height = {H};\n")
    out.write("// Index with glyph_index(codepoint); each row's low 6 bits, MSB = left.\n")
    out.write(f"inline constexpr std::uint8_t glyphs[{len(rows)}][{H}] = {{\n")
    for code, glyph in rows:
        label = chr(code) if chr(code).isprintable() and code != 0x5C else f"U+{code:02X}"
        out.write("    {" + ",".join(f"0x{b:02x}" for b in glyph) + f"}}, // {label}\n")
    out.write("};\n")
    out.write("inline constexpr int glyph_index(std::uint32_t c) {\n")
    out.write("    if (c >= 32 && c < 127) return int(c - 32);\n")
    out.write("    if (c >= 0xA0 && c <= 0xFF) return int(c - 0xA0 + 95);\n")
    out.write("    return int('?' - 32);\n}\n} // namespace pd3ds::font\n")
